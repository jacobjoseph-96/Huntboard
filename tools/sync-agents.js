#!/usr/bin/env node
// Writes every AI tool's own instruction, skill, command and MCP files from the single source in agent/.
//
//   node tools/sync-agents.js           write/refresh all files
//   node tools/sync-agents.js --check   exit 1 if the committed files (AGENTS.md, CLAUDE.md, GEMINI.md) are out of date
//   node tools/sync-agents.js --quiet   no output unless something fails
//
// Edit agent/rules.md, agent/skills/*, agent/mcp.json, agent/platforms.json, never the generated copies.

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const AGENT = path.join(ROOT, 'agent');
const args = process.argv.slice(2);
const CHECK = args.includes('--check');
const QUIET = args.includes('--quiet');
const IS_WIN = process.platform === 'win32';

const MD_HEADER = '<!-- GENERATED by tools/sync-agents.js from agent/. Edit the files in agent/ and run `npm run sync`. -->';
const COMMITTED = ['AGENTS.md', 'CLAUDE.md', 'GEMINI.md'];

function read(file) {
  return fs.readFileSync(file, 'utf8').replace(/^﻿/, '').replace(/\r\n/g, '\n');
}

function parseFrontmatter(text) {
  const m = text.match(/^---\n([\s\S]*?)\n---\n?/);
  if (!m) return { meta: {}, body: text, raw: '' };
  const meta = {};
  let key = null;
  for (const line of m[1].split('\n')) {
    const kv = line.match(/^([A-Za-z_-]+):\s*(.*)$/);
    if (kv) {
      key = kv[1];
      meta[key] = kv[2].replace(/^>-?\s*$/, '').replace(/^["']|["']$/g, '');
    } else if (key && line.trim()) {
      meta[key] = `${meta[key]} ${line.trim()}`.trim();
    }
  }
  return { meta, body: text.slice(m[0].length), raw: m[0] };
}

function loadSkills() {
  const dir = path.join(AGENT, 'skills');
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true })
    .filter((d) => d.isDirectory() && fs.existsSync(path.join(dir, d.name, 'SKILL.md')))
    .map((d) => {
      const text = read(path.join(dir, d.name, 'SKILL.md'));
      const { meta, body, raw } = parseFrontmatter(text);
      if (!meta.name || !meta.description) throw new Error(`agent/skills/${d.name}/SKILL.md needs "name" and "description" frontmatter.`);
      if (meta.name !== d.name) throw new Error(`agent/skills/${d.name}: frontmatter name "${meta.name}" must equal the folder name.`);
      const files = [];
      const walk = (abs, rel) => {
        for (const e of fs.readdirSync(abs, { withFileTypes: true })) {
          const r = rel ? `${rel}/${e.name}` : e.name;
          if (e.isDirectory()) walk(path.join(abs, e.name), r);
          else if (r !== 'SKILL.md') files.push(r);
        }
      };
      walk(path.join(dir, d.name), '');
      return { name: d.name, meta, body, frontmatter: raw, files, dir: path.join(dir, d.name) };
    })
    .sort((a, b) => a.name.localeCompare(b.name));
}

function firstSentence(s) {
  const m = String(s).match(/^(.*?\.)(\s|$)/);
  return (m ? m[1] : s).trim();
}

function rulesText(skills) {
  const table = ['| Skill | What it does |', '|---|---|', ...skills.map((s) => `| \`${s.name}\` | ${firstSentence(s.meta.description)} |`)].join('\n');
  return read(path.join(AGENT, 'rules.md')).replace('{{SKILLS_TABLE}}', table);
}

function workspacePath() {
  return path.resolve(process.env.HUNTBOARD_WORKSPACE || path.join(ROOT, 'workspace')).split(path.sep).join('/');
}

function mcpServers() {
  const src = JSON.parse(read(path.join(AGENT, 'mcp.json'))).servers;
  const out = {};
  for (const [name, s] of Object.entries(src)) {
    const a = s.args.map((x) => x.replace('{workspace}', workspacePath()));
    out[name] = IS_WIN && ['npx', 'npm', 'node'].includes(s.command) && s.command !== 'node'
      ? { command: 'cmd', args: ['/c', s.command, ...a] }
      : { command: s.command, args: a };
  }
  return out;
}

function toml(v) {
  return Array.isArray(v) ? `[${v.map(toml).join(', ')}]` : JSON.stringify(String(v));
}

function skillPrompt(s) {
  return `Use the Huntboard skill "${s.name}": read agent/skills/${s.name}/SKILL.md and follow it exactly.`;
}

function buildOutputs() {
  const skills = loadSkills();
  const rules = rulesText(skills);
  const platforms = JSON.parse(read(path.join(AGENT, 'platforms.json')));
  const out = new Map();
  const md = (p, body) => out.set(p, `${MD_HEADER}\n\n${body.trim()}\n`);

  // Instructions
  md('AGENTS.md', rules);
  md('CLAUDE.md', '@AGENTS.md');
  md('GEMINI.md', rules);

  // Skills: same SKILL.md for every tool that reads Agent Skills folders.
  const skillDirs = [...new Set(Object.values(platforms.tools).map((t) => t.skills).filter(Boolean))];
  for (const s of skills) {
    for (const base of skillDirs) {
      out.set(`${base}/${s.name}/SKILL.md`, `${s.frontmatter}${MD_HEADER}\n\n${s.body.trim()}\n`);
      for (const f of s.files) out.set(`${base}/${s.name}/${f}`, fs.readFileSync(path.join(s.dir, f)));
    }
    // Slash commands for tools that use command files.
    const desc = firstSentence(s.meta.description);
    out.set(`.gemini/commands/${s.name}.toml`, `# GENERATED by tools/sync-agents.js from agent/\ndescription = ${toml(desc)}\nprompt = """\n${skillPrompt(s)}\n{{args}}\n"""\n`);
    out.set(`.opencode/command/${s.name}.md`, `---\ndescription: ${desc}\n---\n${MD_HEADER}\n\n${skillPrompt(s)}\n\n$ARGUMENTS\n`);
    out.set(`.cursor/commands/${s.name}.md`, `${MD_HEADER}\n\n${skillPrompt(s)}\n`);
    out.set(`.github/prompts/${s.name}.prompt.md`, `---\ndescription: ${desc}\nmode: agent\n---\n${MD_HEADER}\n\n${skillPrompt(s)}\n`);
    out.set(`.agents/workflows/${s.name}.md`, `---\ndescription: ${desc}\n---\n${MD_HEADER}\n\n${skillPrompt(s)}\n`);
  }

  // MCP servers (machine-specific, gitignored)
  const servers = mcpServers();
  const json = (p, v) => out.set(p, JSON.stringify(v, null, 2) + '\n');
  json('.mcp.json', { mcpServers: servers });
  json('.agents/plugins/job-browser/plugin.json', { name: 'job-browser' });
  json('.agents/plugins/job-browser/mcp_config.json', { mcpServers: servers });
  json('.gemini/settings.json', {
    mcpServers: servers,
    hooks: { SessionStart: [{ hooks: [{ type: 'command', command: 'node tools/hunt.js inbox --hook' }] }] },
  });
  json('.cursor/mcp.json', { mcpServers: servers });
  json('.vscode/mcp.json', { servers: Object.fromEntries(Object.entries(servers).map(([k, v]) => [k, { type: 'stdio', ...v }])) });
  json('opencode.json', {
    $schema: 'https://opencode.ai/config.json',
    mcp: Object.fromEntries(Object.entries(servers).map(([k, v]) => [k, { type: 'local', command: [v.command, ...v.args], enabled: true }])),
  });
  out.set('.codex/config.toml', `# GENERATED by tools/sync-agents.js from agent/\n${Object.entries(servers)
    .map(([k, v]) => `[mcp_servers.${k}]\ncommand = ${toml(v.command)}\nargs = ${toml(v.args)}\n`).join('\n')}`);

  // Claude Code: allow the hunt tool and the browser without prompts, show the inbox at session start.
  json('.claude/settings.json', {
    permissions: {
      allow: [
        ...platforms.allow.commands.flatMap((c) => [`Bash(${c} *)`, `PowerShell(${c} *)`]),
        ...Object.keys(servers).map((k) => `mcp__${k}`),
        'WebSearch',
        'WebFetch',
      ],
    },
    enabledMcpjsonServers: Object.keys(servers),
    hooks: { SessionStart: [{ hooks: [{ type: 'command', command: 'node tools/hunt.js inbox --hook' }] }] },
  });
  return out;
}

function main() {
  let outputs;
  try {
    outputs = buildOutputs();
  } catch (err) {
    console.error(`sync-agents: ${err.message}`);
    process.exit(2);
  }
  if (CHECK) {
    const stale = COMMITTED.filter((p) => {
      const f = path.join(ROOT, p);
      return !fs.existsSync(f) || read(f) !== outputs.get(p);
    });
    if (stale.length) {
      console.error(`Out of date: ${stale.join(', ')}. Run "npm run sync" and commit the result.`);
      process.exit(1);
    }
    if (!QUIET) console.log('Generated instruction files are up to date.');
    return;
  }
  let written = 0;
  for (const [rel, content] of outputs) {
    const file = path.join(ROOT, rel);
    const buf = Buffer.isBuffer(content) ? content : Buffer.from(content, 'utf8');
    if (fs.existsSync(file) && fs.readFileSync(file).equals(buf)) continue;
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, buf);
    written++;
  }
  if (!QUIET) console.log(`Synced AI instructions: ${written} file(s) updated, ${outputs.size} in total.`);
}

main();
